public class IntOperations {
    public static int addTwoIntegers(int one, int two) {
        return one + two;
    }
    public static int subtractTwoIntegers(int one, int two) {
        return one - two;
    }
    public static int multiplyTwoIntegers(int one, int two) {
        return one * two;
    }
    public static int divideTwoIntegers(int one, int two) {
        return one / two;
    }
}